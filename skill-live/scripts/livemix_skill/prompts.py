_BUILTIN_BY_NAME: Dict[str, PromptEntry] = {entry.name: entry for entry in BUILTIN_PROMPTS}


def builtin_names() -> List[str]:
    return [entry.name for entry in BUILTIN_PROMPTS]


def get_builtin(name: str) -> Optional[PromptEntry]:
    return _BUILTIN_BY_NAME.get(name.strip())


def resolve_prompt(spec: str, prompt_dir: str = "") -> PromptEntry:
    """把 --prompt 参数解析为提示词内容。

    支持：
    1. 内置提示词名称（如「默认提示词」「财经类直播」）；
    2. 文件路径（.md / .txt）；
    3. prompt_dir 下的 <spec>.md；
    4. 含换行的原始提示词文本（方便 Agent 直接传入）。
    """
    text = (spec or "").strip()
    if not text:
        raise ValueError("未指定选片提示词。可用内置提示词：" + "、".join(builtin_names()))

    builtin = get_builtin(text)
    if builtin:
        return builtin

    candidate = os.path.abspath(os.path.expanduser(text))
    if os.path.isfile(candidate):
        with open(candidate, "r", encoding="utf-8", errors="replace") as handle:
            content = handle.read().strip()
        if not content:
            raise ValueError(f"提示词文件为空：{candidate}")
        return PromptEntry(
            name=os.path.splitext(os.path.basename(candidate))[0],
            note=candidate,
            summary=content.replace("\n", " ")[:64],
            edited_at="",
            content=content,
        )

    if prompt_dir:
        for suffix in (".md", ".txt"):
            path = os.path.join(prompt_dir, text + suffix)
            if os.path.isfile(path):
                with open(path, "r", encoding="utf-8", errors="replace") as handle:
                    content = handle.read().strip()
                if content:
                    return PromptEntry(
                        name=text, note=path,
                        summary=content.replace("\n", " ")[:64],
                        edited_at="", content=content,
                    )

    if "\n" in text and len(text) > 20:
        return PromptEntry(
            name="自定义提示词", note="inline",
            summary=text.replace("\n", " ")[:64],
            edited_at="", content=text,
        )

    raise ValueError(
        f"找不到提示词「{text}」。可用内置提示词：" + "、".join(builtin_names())
    )


def summarize(content: str, max_length: int = 64) -> str:
    text = " ".join(content.split())
    if len(text) > max_length:
        return text[:max_length] + "……"
    return text
